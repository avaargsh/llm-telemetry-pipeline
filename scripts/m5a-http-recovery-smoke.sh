#!/usr/bin/env bash
# M5a HTTP -> PG Ledger/Outbox -> Kafka -> ClickHouse fault/recovery proof.
# Disposable CI-only Compose project; never run against production data.
set -euo pipefail
cd "$(dirname "$0")/.."
export COMPOSE_PROJECT_NAME="llmtelemetry-m5a-${GITHUB_RUN_ID:-local}-$$"
compose=(docker compose -f deployments/docker-compose.yml)
tmp="$(mktemp -d)"
api_pid='' ; worker_pid='' ; relay_pid=''
cleanup() {
  code=$?
  trap - EXIT
  for pid in "$api_pid" "$worker_pid" "$relay_pid"; do
    if [[ -n "$pid" ]]; then
      kill "$pid" 2>/dev/null || true
      wait "$pid" 2>/dev/null || true
    fi
  done
  if ((code != 0)); then
    echo "M5a HTTP recovery FAILED (exit $code)" >&2
    for logfile in "$tmp/api.log" "$tmp/consumer.log" "$tmp/relay.log"; do
      [[ ! -f "$logfile" ]] || tail -80 "$logfile" >&2
    done
    "${compose[@]}" ps >&2 || true
    "${compose[@]}" logs --tail 60 kafka postgres clickhouse >&2 || true
  fi
  "${compose[@]}" down -v >/dev/null 2>&1 || true
  rm -rf "$tmp"
  exit "$code"
}
trap cleanup EXIT

kafka_ready() {
  "${compose[@]}" exec -T kafka /opt/kafka/bin/kafka-topics.sh \
    --bootstrap-server kafka:19092 --list >/dev/null 2>&1
}
pg_count() {
  "${compose[@]}" exec -T postgres \
    psql -U telemetry -d telemetry -tAc "$1" | tr -d '[:space:]'
}
ch_query() {
  curl -fsS --max-time 5 -u telemetry:localdev-only \
    'http://127.0.0.1:18123/?database=telemetry' \
    --data-binary "$1" | tr -d '[:space:]'
}
post_event() {
  local token="$1" payload="$2"
  local -a args=(--silent --show-error --max-time 10 --output "$tmp/response.json"
    --write-out '%{http_code}' --request POST
    --header 'Content-Type: application/json'
    --data-binary "$payload")
  if [[ -n "$token" ]]; then args+=(--header "Authorization: Bearer $token"); fi
  curl "${args[@]}" 'http://127.0.0.1:18085/v1/usage-events'
}
assert_status() {
  local expected="$1" actual="$2" kind="$3"
  if [[ "$actual" != "$expected" ]]; then
    echo "$kind: expected HTTP $expected got $actual" >&2
    cat "$tmp/response.json" >&2 || true
    exit 1
  fi
}

"${compose[@]}" up -d
for i in $(seq 1 90); do
  if kafka_ready &&
     [[ "$(pg_count 'SELECT count(*) FROM usage_ledger' 2>/dev/null)" == 0 ]] &&
     [[ "$(ch_query 'SELECT 1 FORMAT TabSeparatedRaw' 2>/dev/null)" == 1 ]]; then
    break
  fi
  if (( i == 90 )); then echo 'Compose services not ready or not empty' >&2; exit 1; fi
  sleep 2
done
bash scripts/bootstrap-topics.sh
go build -o "$tmp/generator" ./cmd/event-generator
go build -o "$tmp/api" ./cmd/usage-ingest-api
go build -o "$tmp/relay" ./cmd/outbox-relay
go build -o "$tmp/consumer" ./cmd/ingest-worker
go build -o "$tmp/reconciler" ./cmd/reconciler

# Credentials are disposable and scoped to the exact tenant/project pairs
# generated by SyntheticUsageEvent for index 0..15.
tokens=()
credentials='['
for i in $(seq 0 7); do
  token="$(openssl rand -hex 32)"
  tokens+=("$token")
  printf -v record '{"token":"%s","tenant_id":"tenant_%03d","project_id":"project_%03d"}' \
    "$token" "$((i % 4 + 1))" "$((i + 1))"
  if (( i > 0 )); then credentials+=','; fi
  credentials+="$record"
done
credentials+=']'
mapfile -t events < <("$tmp/generator" --count 16 --seed "m5a-${GITHUB_RUN_ID:-local}" \
   --start 2026-11-21T10:00:00Z)
[[ "${#events[@]}" == 16 ]] || { echo "generator returned ${#events[@]} lines" >&2; exit 1; }

# Prove that the API is independent of Kafka availability.
"${compose[@]}" stop kafka
DATABASE_URL='postgres://telemetry:localdev-only@localhost:15432/telemetry?sslmode=disable' \
  USAGE_INGEST_CREDENTIALS_JSON="$credentials" \
  "$tmp/api" --listen 127.0.0.1:18085 > "$tmp/api.log" 2>&1 &
api_pid=$!
for i in $(seq 1 40); do
  if curl -fsS --max-time 2 'http://127.0.0.1:18085/healthz' > /dev/null 2>&1; then break; fi
  if ! kill -0 "$api_pid" 2>/dev/null; then echo 'API exited before ready' >&2; exit 1; fi
  if (( i == 40 )); then echo 'API readiness timeout' >&2; exit 1; fi
  sleep 1
done

for i in $(seq 0 15); do
  status="$(post_event "${tokens[$((i % 8))]}" "${events[$i]}")"
  assert_status 201 "$status" "event $i create"
  grep -Fq '"result":"created"' "$tmp/response.json" || { echo "unexpected create response" >&2; exit 1; }
done
assert_status 200 "$(post_event "${tokens[0]}" "${events[0]}")" 'identical retry'
grep -Fq '"result":"duplicate"' "$tmp/response.json" || exit 1
assert_status 403 "$(post_event "${tokens[1]}" "${events[0]}")" 'cross-tenant denial'
assert_status 401 "$(post_event '' "${events[0]}")" 'missing credential'
ledger_count="$(pg_count 'SELECT count(*) FROM usage_ledger')"
pending_count="$(pg_count 'SELECT count(*) FROM event_outbox WHERE published_at IS NULL')"
[[ "$ledger_count" == 16 && "$pending_count" == 16 ]] || {
  echo "Kafka offline: expected ledger=16 pending=16, got $ledger_count/$pending_count" >&2; exit 1;
}
echo "M5a: Kafka offline persisted ledger=$ledger_count pending=$pending_count; duplicate and cross-tenant requests did not add records"

"${compose[@]}" start kafka
for i in $(seq 1 90); do
  if kafka_ready; then break; fi
  if (( i == 90 )); then echo 'Kafka recovery timed out' >&2; exit 1; fi
  sleep 2
done
"$tmp/consumer" --batch-size 8 > "$tmp/consumer.log" 2>&1 &
worker_pid=$!
"$tmp/relay" --worker "m5a-${GITHUB_RUN_ID:-local}-$$" > "$tmp/relay.log" 2>&1 &
relay_pid=$!
for i in $(seq 1 90); do
  published="$(pg_count 'SELECT count(*) FROM event_outbox WHERE published_at IS NOT NULL')"
  trusted="$(ch_query 'SELECT count(*) FROM inference_events_dedup_v1 FORMAT TabSeparatedRaw' 2>/dev/null || echo unknown)"
  if [[ "$published" == 16 && "$trusted" == 16 ]]; then break; fi
  if ! kill -0 "$worker_pid" 2>/dev/null || ! kill -0 "$relay_pid" 2>/dev/null; then
    echo 'consumer or relay exited during replay' >&2; exit 1;
  fi
  if (( i == 90 )); then echo "recovery timeout: published=$published trusted=$trusted" >&2; exit 1; fi
  sleep 2
done
[[ "$(pg_count 'SELECT count(*) FROM usage_ledger')" == 16 ]]
[[ "$(pg_count 'SELECT count(*) FROM event_outbox')" == 16 ]]
[[ "$(ch_query 'SELECT count(*) FROM inference_events_integrity_v1 FORMAT TabSeparatedRaw')" == 0 ]]

POSTGRES_DSN='postgres://telemetry:localdev-only@localhost:15432/telemetry?sslmode=disable' \
CLICKHOUSE_HTTP='http://localhost:18123' CLICKHOUSE_USER=telemetry \
CLICKHOUSE_PASSWORD=localdev-only \
"$tmp/reconciler" --start '2026-11-21T10:00:00Z' --end '2026-11-21T10:00:01Z' \
   --grace 0s --max-records 100 > "$tmp/reconcile.json"
python3 - "$tmp/reconcile.json" <<'PY'
import json, sys
report = json.load(open(sys.argv[1], encoding="utf-8"))
assert report["result"] == "PASS", report
print("M5a reconciliation result: PASS")
PY
echo "PASS M5a: authenticated HTTP accepted 16 durable events while Kafka down; after recovery PG Outbox/CH trusted projection reconciled without duplicate billing"
